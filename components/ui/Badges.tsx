import { Award, Flame, Gem, Sparkles, Trophy } from "lucide-react";
import { priceSymbols } from "@/lib/utils";

const AWARD_META: Record<string, { label: string; className: string; icon: typeof Award }> = {
  "best-of-the-best": { label: "Best of the Best", className: "bg-ink text-bg", icon: Trophy },
  "travelers-choice": { label: "Travelers' Choice", className: "bg-brand-100 text-brand-800 dark:bg-brand-900/60 dark:text-brand-200", icon: Award },
  "hidden-gem": { label: "Hidden Gem", className: "bg-violet-100 text-violet-800 dark:bg-violet-900/50 dark:text-violet-200", icon: Gem },
  trending: { label: "Trending", className: "bg-coral-100 text-coral-700 dark:bg-coral-700/30 dark:text-coral-200", icon: Flame },
};

export function AwardBadge({ award, compact = false }: { award: string; compact?: boolean }) {
  const meta = AWARD_META[award];
  if (!meta) return null;
  const Icon = meta.icon;
  return (
    <span className={`badge ${meta.className}`} title={meta.label}>
      <Icon className="size-3" />
      {!compact && meta.label}
    </span>
  );
}

export function AwardList({ awards, max = 2, compact = false }: { awards: string[]; max?: number; compact?: boolean }) {
  const order = ["best-of-the-best", "travelers-choice", "hidden-gem", "trending"];
  const sorted = [...awards].sort((a, b) => order.indexOf(a) - order.indexOf(b)).slice(0, max);
  if (!sorted.length) return null;
  return (
    <span className="inline-flex flex-wrap gap-1.5">
      {sorted.map((a) => (
        <AwardBadge key={a} award={a} compact={compact} />
      ))}
    </span>
  );
}

export function PriceLevel({ level, className = "" }: { level: number; className?: string }) {
  const s = priceSymbols(level);
  return (
    <span className={`font-medium tracking-tight ${className}`} title={`Price level ${level} of 4`}>
      {s}
      <span className="opacity-30">{"$".repeat(4 - s.length)}</span>
    </span>
  );
}

export function AiBadge({ provider, className = "" }: { provider?: string; className?: string }) {
  return (
    <span className={`badge ai-gradient text-white ${className}`} title={provider === "claude" ? "Generated by Claude" : "Generated by Wayfarer's local AI engine"}>
      <Sparkles className="size-3" />
      {provider === "claude" ? "Claude AI" : "AI"}
    </span>
  );
}

export function TrustBadge({ score }: { score: number }) {
  const level = score >= 70 ? "high" : score >= 40 ? "medium" : "low";
  const cls =
    level === "high"
      ? "bg-brand-50 text-brand-700 dark:bg-brand-900/40 dark:text-brand-300"
      : level === "medium"
        ? "bg-amber-50 text-amber-700 dark:bg-amber-900/30 dark:text-amber-300"
        : "bg-red-50 text-red-700 dark:bg-red-900/30 dark:text-red-300";
  return (
    <span className={`badge ${cls}`} title={`AI authenticity score ${score}/100`}>
      {level === "high" ? "Verified pattern" : level === "medium" ? "Unverified" : "Low trust"} · {score}
    </span>
  );
}
