"use client";

import { Bed, Copy, Footprints, Lightbulb, Loader2, Printer, RefreshCw, Save, Train, Utensils } from "lucide-react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { LazyMap, type MapMarker } from "@/components/map/LazyMap";
import { useApp } from "@/components/providers/AppProviders";
import { AiBadge } from "@/components/ui/Badges";
import { SmartImage } from "@/components/ui/SmartImage";
import { WeatherIcon } from "@/components/ui/WeatherIcon";
import { haversineKm, travelMinutes, travelMode } from "@/lib/geo";
import type { WeatherIcon as WIcon } from "@/lib/services/weather";
import type { PlaceCardData, PlanRequest } from "@/lib/types";
import { cn, formatDuration, formatUsd, imgUrl } from "@/lib/utils";
import type { PlanResult } from "./Planner";

export interface PlanWeather {
  date: string;
  tmax: number;
  tmin: number;
  precipProb: number;
  summary: string;
  icon: WIcon;
  source: "forecast" | "climate";
}

export const DAY_COLORS = ["#0f766e", "#ea580c", "#7c3aed", "#db2777", "#2563eb", "#ca8a04", "#16a34a", "#dc2626", "#0891b2", "#9333ea", "#65a30d", "#c2410c", "#4f46e5", "#be123c"];

export function ItineraryView({ result, request, signedIn, onRegenerate }: { result: PlanResult; request: PlanRequest; signedIn: boolean; onRegenerate: () => void }) {
  const { toast } = useApp();
  const router = useRouter();
  const { itinerary: it, places, weather, destination } = result;
  const byId = useMemo(() => new Map(places.map((p) => [p.id, p])), [places]);
  const [day, setDay] = useState<number | "all">(1);
  const [saving, setSaving] = useState(false);
  const hotel = it.hotelPlaceId ? byId.get(it.hotelPlaceId) : null;

  const days = day === "all" ? it.days : it.days.filter((d) => d.day === day);
  const markers: MapMarker[] = days.flatMap((d) =>
    d.stops
      .filter((s) => s.placeId && byId.has(s.placeId))
      .map((s, i) => {
        const p = byId.get(s.placeId!)!;
        return {
          id: `${d.day}-${i}-${p.id}`,
          lat: p.lat,
          lng: p.lng,
          title: p.name,
          subtitle: `Day ${d.day} · ${s.startTime}`,
          href: `/place/${p.slug}`,
          image: p.image ? imgUrl(p.image, 330) : null,
          label: day === "all" ? d.day : i + 1,
          color: DAY_COLORS[(d.day - 1) % DAY_COLORS.length],
        };
      })
  );
  if (hotel) markers.push({ id: "hotel", lat: hotel.lat, lng: hotel.lng, title: hotel.name, subtitle: "Your hotel", href: `/place/${hotel.slug}`, image: hotel.image ? imgUrl(hotel.image, 330) : null, label: "H", color: "#111827" });
  const polylines = days.map((d) => ({
    color: DAY_COLORS[(d.day - 1) % DAY_COLORS.length],
    points: [
      ...(hotel ? [[hotel.lat, hotel.lng] as [number, number]] : []),
      ...d.stops.filter((s) => s.placeId && byId.has(s.placeId)).map((s) => [byId.get(s.placeId!)!.lat, byId.get(s.placeId!)!.lng] as [number, number]),
    ],
  }));

  const save = async () => {
    if (!signedIn) {
      try {
        sessionStorage.setItem("wf-pending-plan", JSON.stringify({ request, itinerary: it }));
      } catch {}
      router.push(`/login?next=${encodeURIComponent("/trips?import=1")}`);
      return;
    }
    setSaving(true);
    const r = await fetch("/api/trips/from-plan", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ request, itinerary: it }) });
    setSaving(false);
    if (!r.ok) return toast((await r.json()).error || "Couldn't save", "error");
    const { id } = await r.json();
    toast("Trip saved — you can now edit, reorder and share it");
    router.push(`/trips/${id}`);
  };

  const copyText = async () => {
    const txt = [
      it.title,
      it.summary,
      "",
      ...it.days.flatMap((d) => [`Day ${d.day}: ${d.title}`, ...d.stops.map((s) => `  ${s.startTime}  ${s.title}${s.note ? ` — ${s.note}` : ""}`), ""]),
      `Estimated total: ${formatUsd(it.estimatedCostUsd.total)}`,
    ].join("\n");
    await navigator.clipboard.writeText(txt);
    toast("Itinerary copied to clipboard");
  };

  const cost = it.estimatedCostUsd;
  const costRows = [
    ["Stay", cost.lodging, "bg-violet-500"],
    ["Food", cost.food, "bg-coral-500"],
    ["Activities", cost.activities, "bg-brand-500"],
    ["Transport", cost.transport, "bg-sky-500"],
  ] as const;

  return (
    <div className="container-page py-10 animate-fade-up">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="max-w-3xl">
          <div className="flex items-center gap-2">
            <AiBadge provider={it.provider} />
            <span className="text-xs text-muted">{it.provider === "claude" ? "Written by Claude, routed by Wayfarer" : "Generated by Wayfarer's planning engine"}</span>
          </div>
          <h2 className="mt-2 font-display text-3xl font-semibold tracking-tight sm:text-4xl">{it.title}</h2>
          <p className="mt-2 text-ink-2">{it.summary}</p>
        </div>
        <div className="no-print flex flex-wrap gap-2">
          <button onClick={save} disabled={saving} className="btn btn-primary">
            {saving ? <Loader2 className="size-4 animate-spin" /> : <Save className="size-4" />} {signedIn ? "Save trip" : "Sign in to save"}
          </button>
          <button onClick={onRegenerate} className="btn btn-outline">
            <RefreshCw className="size-4" /> Regenerate
          </button>
          <button onClick={copyText} className="btn btn-outline btn-icon" aria-label="Copy as text" title="Copy as text">
            <Copy className="size-4" />
          </button>
          <button onClick={() => window.print()} className="btn btn-outline btn-icon" aria-label="Print" title="Print">
            <Printer className="size-4" />
          </button>
        </div>
      </div>

      <div className="mt-8 grid gap-8 lg:grid-cols-[1fr_420px]">
        <div className="min-w-0">
          <div className="no-print scrollbar-none mb-5 flex gap-1.5 overflow-x-auto pb-1">
            {it.days.map((d) => {
              const w = weather[d.day - 1];
              return (
                <button key={d.day} onClick={() => setDay(d.day)} className="chip shrink-0" data-active={day === d.day}>
                  <span className="size-2.5 rounded-full" style={{ background: DAY_COLORS[(d.day - 1) % DAY_COLORS.length] }} />
                  Day {d.day}
                  {w && (
                    <span className="inline-flex items-center gap-0.5 opacity-80">
                      <WeatherIcon icon={w.icon} className="size-3.5" />
                      {w.tmax}°
                    </span>
                  )}
                </button>
              );
            })}
            <button onClick={() => setDay("all")} className="chip shrink-0" data-active={day === "all"}>
              All days
            </button>
          </div>

          {hotel && (
            <Link href={`/place/${hotel.slug}`} className="card mb-6 flex items-center gap-3 p-3 hover:shadow-lift">
              <SmartImage image={hotel.image} alt={hotel.name} width={330} className="size-14 shrink-0 rounded-xl" />
              <div className="min-w-0 flex-1">
                <div className="flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wider text-muted">
                  <Bed className="size-3.5" /> Where you&apos;ll stay
                </div>
                <div className="truncate font-semibold">{hotel.name}</div>
                <div className="text-xs text-muted">
                  {hotel.category} · ★ {hotel.rating.toFixed(1)} · {formatUsd(hotel.priceUsd)}/night
                </div>
              </div>
            </Link>
          )}

          <div className="space-y-10">
            {days.map((d) => {
              const w = weather[d.day - 1];
              let prev: PlaceCardData | null = hotel || null;
              return (
                <section key={d.day}>
                  <div className="flex flex-wrap items-end justify-between gap-2">
                    <div>
                      <div className="text-xs font-semibold uppercase tracking-wider" style={{ color: DAY_COLORS[(d.day - 1) % DAY_COLORS.length] }}>
                        Day {d.day}
                        {w ? ` · ${new Date(w.date + "T12:00:00Z").toLocaleDateString("en-US", { weekday: "long", month: "short", day: "numeric", timeZone: "UTC" })}` : ""}
                      </div>
                      <h3 className="font-display text-2xl font-semibold">{d.title}</h3>
                    </div>
                    {w && (
                      <div className="flex items-center gap-2 rounded-full bg-surface-2 px-3 py-1.5 text-sm">
                        <WeatherIcon icon={w.icon} className="size-5" />
                        {w.tmax}° / {w.tmin}° · {w.precipProb}% rain
                        <span className="text-[10px] text-muted">{w.source === "climate" ? "avg" : "forecast"}</span>
                      </div>
                    )}
                  </div>
                  <ol className="relative mt-5 space-y-4 border-l-2 border-dashed border-line pl-6">
                    {d.stops.map((s, i) => {
                      const p = s.placeId ? byId.get(s.placeId) : null;
                      const km = p && prev ? haversineKm(prev, p) : null;
                      const hint =
                        km != null && km > 0.05 ? (
                          <div className="-mt-1 mb-2 flex items-center gap-1.5 text-xs text-muted">
                            {travelMode(km) === "walk" ? <Footprints className="size-3.5" /> : <Train className="size-3.5" />}
                            {travelMinutes(km)} min {travelMode(km) === "walk" ? "walk" : travelMode(km) === "transit" ? "by transit" : "drive"} · {km < 1 ? `${Math.round(km * 1000)} m` : `${km.toFixed(1)} km`}
                          </div>
                        ) : null;
                      if (p) prev = p;
                      return (
                        <li key={i} className="relative">
                          <span
                            className="absolute -left-[35px] top-3 grid size-6 place-items-center rounded-full border-2 border-bg text-[10px] font-bold text-white"
                            style={{ background: s.kind === "meal" ? "#ea580c" : DAY_COLORS[(d.day - 1) % DAY_COLORS.length] }}
                          >
                            {s.kind === "meal" ? <Utensils className="size-3" /> : i + 1}
                          </span>
                          {hint}
                          <div className="card flex gap-3 p-3">
                            {p ? <SmartImage image={p.image} alt={p.name} width={330} className="size-20 shrink-0 rounded-xl sm:size-24" /> : null}
                            <div className="min-w-0 flex-1">
                              <div className="flex flex-wrap items-center gap-x-2 text-xs text-muted">
                                <span className="font-semibold text-ink">{s.startTime}</span>
                                <span>· {formatDuration(s.durationMin)}</span>
                                {s.costUsd > 0 && <span>· ~{formatUsd(s.costUsd)}</span>}
                              </div>
                              {p ? (
                                <Link href={`/place/${p.slug}`} className="block truncate font-semibold hover:text-brand-700">
                                  {s.title}
                                </Link>
                              ) : (
                                <div className="font-semibold">{s.title}</div>
                              )}
                              {p && (
                                <div className="text-xs text-muted">
                                  {p.category} · ★ {p.rating.toFixed(1)} ({p.reviewCount})
                                </div>
                              )}
                              {s.note && <p className="mt-1 text-sm text-ink-2">{s.note}</p>}
                            </div>
                          </div>
                        </li>
                      );
                    })}
                  </ol>
                </section>
              );
            })}
          </div>
        </div>

        <aside className="space-y-6">
          <div className="lg:sticky lg:top-24 lg:space-y-6">
            <LazyMap markers={markers} polylines={polylines} className="h-[380px]" />
            <div className="card mt-6 p-5 lg:mt-0">
              <div className="flex items-baseline justify-between">
                <div className="text-sm font-semibold">Estimated cost</div>
                <div className="text-xs text-muted">{request.travelers} traveler{request.travelers > 1 ? "s" : ""}</div>
              </div>
              <div className="mt-1 font-display text-3xl font-semibold">{formatUsd(cost.total)}</div>
              <div className="text-sm text-muted">{formatUsd(cost.perPerson)} per person · excl. flights</div>
              <div className="mt-4 flex h-2.5 overflow-hidden rounded-full">
                {costRows.map(([l, v, c]) => (
                  <div key={l} className={c} style={{ width: `${(v / Math.max(1, cost.total)) * 100}%` }} />
                ))}
              </div>
              <div className="mt-3 space-y-1.5 text-sm">
                {costRows.map(([l, v, c]) => (
                  <div key={l} className="flex items-center gap-2">
                    <span className={cn("size-2.5 rounded-full", c)} />
                    <span className="text-muted">{l}</span>
                    <span className="ml-auto font-semibold">{formatUsd(v)}</span>
                  </div>
                ))}
              </div>
            </div>
            {it.tips.length > 0 && (
              <div className="card mt-6 p-5 lg:mt-0">
                <div className="flex items-center gap-2 text-sm font-semibold">
                  <Lightbulb className="size-4 text-sun-500" /> Tips for this trip
                </div>
                <ul className="mt-3 space-y-2 text-sm text-ink-2">
                  {it.tips.map((t, i) => (
                    <li key={i} className="flex gap-2">
                      <span className="text-brand-600">•</span>
                      {t}
                    </li>
                  ))}
                </ul>
              </div>
            )}
            <p className="text-center text-xs text-muted">
              Prices and times are estimates. Currency: {destination.currency.symbol} {destination.currency.code}.
            </p>
          </div>
        </aside>
      </div>
    </div>
  );
}
